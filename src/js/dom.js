export function icon(name, size = 16) {
  const ns = "http://www.w3.org/2000/svg";
  const svg = document.createElementNS(ns, "svg");
  const filled = name in FILLED;
  svg.setAttribute("class", filled ? "icon icon-fill" : "icon");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", size);
  svg.setAttribute("height", size);
  svg.setAttribute("aria-hidden", "true");
  for (const d of (filled ? FILLED : ICONS)[name] ?? []) {
    const path = document.createElementNS(ns, "path");
    path.setAttribute("d", d);
    svg.append(path);
  }
  return svg;
}

/** A design checkbox: a real input for keyboard and screen readers, drawn as a box. */
export function checkbox({ checked, disabled, onChange, label, size = 20 }) {
  return [
    el("input", {
      type: "checkbox",
      className: "check-input",
      checked,
      disabled,
      "aria-label": label,
      onchange: (event) => onChange(event.target.checked),
    }),
    el("span", { className: size === 22 ? "check check-lg" : "check", "aria-hidden": "true" }, icon("check", size === 22 ? 15 : 14)),
  ];
}

let toastTimer;
/** A short message at the bottom of the window. */
export function toast(message) {
  const node = $("toast");
  node.textContent = message;
  node.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => {
    node.hidden = true;
  }, 4200);
}
